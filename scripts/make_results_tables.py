"""Write the result tables of README.md and docs/7_results.md from the files in results/, so no number in them is typed
by hand.

Run from the repository root:  python scripts/make_results_tables.py          (rewrites the tables in place)
                               python scripts/make_results_tables.py --check  (exit 1 if a doc is out of date)

Reads:   results/distill/logit/comparison_from2010.csv and results/distill/networks/{metrics,comparison}.csv (the
         single tone Hd, the main result), results/doctype/logit/comparison_{from2010,full}.csv,
         results/doctype/logit/verdict.json, results/doctype/networks/{metrics,comparison,small_sample}.csv.
Writes:  the text between the "headline:start" and "headline:end" markers in README.md, the text between the
         "tables:start" and "tables:end" markers in docs/7_results.md, and the whole of docs/HYPERPARAMETERS.md (from
         results/*/networks/settings_*.json).
Uses the standard library only, so it runs without the project's environment.
"""
import csv
import json
import sys
from datetime import date
from pathlib import Path
from statistics import median

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "results"
DOC = REPO / "docs" / "7_results.md"
HYPER = REPO / "docs" / "HYPERPARAMETERS.md"
README = REPO / "README.md"
START, END = "<!-- tables:start (generated by scripts/make_results_tables.py) -->", "<!-- tables:end -->"
H_START, H_END = "<!-- headline:start (generated by scripts/make_results_tables.py) -->", "<!-- headline:end -->"
L_START, L_END = "<!-- lookback:start (generated by scripts/make_results_tables.py) -->", "<!-- lookback:end -->"
ALPHA = 0.05
HD_ARMS = (("S+M", "No news"), ("placebo-Hd", "Fake tone"), ("S+M+Hd", "Real tone"))
NETWORK_NAMES = {"lstm": "LSTM network", "gru": "GRU network", "tft": "TFT network"}
ARCHS = {"lstm": "LSTM", "gru": "GRU", "tft": "TFT"}
COLUMNS = {"S+M": 24, "S+M+Hd": 26, "S+M+Hs": 30, "placebo-Hs": 30, "shuffled-Hs": 30}


def read_csv(path: Path) -> list[dict]:
    """Rows of a csv file as dicts of strings."""
    with open(path, newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def pct(x: str) -> str:
    """A share such as 0.8370 as '83.7%'."""
    return f"{float(x):.1%}"


def p3(x: str | float) -> str:
    """A p-value with 3 decimals, or 4 below 0.02 so values near 0.01 keep three significant digits."""
    x = float(x)
    return f"{x:.4f}" if x < 0.02 else f"{x:.3f}"


def hd_models() -> list[dict]:
    """The single tone Hd from 2010, one dict per model: its three arms' scores and its three p-values.

    p_main: real tone against no news (ordered logit: one-sided Clark-West; networks: one-sided Newey-West with 8 lags
    on the log-loss difference, Holm-adjusted over the 3 networks). p_fake: placebo against no news, same test, not
    adjusted. p_real_fake: real tone against placebo (networks only; not computed for the ordered logit, so None).
    """
    logit = {r["model"]: r for r in read_csv(RESULTS / "distill" / "logit" / "comparison_from2010.csv")}
    models = [{"name": "Ordered logit", "n": int(logit["S+M"]["n"]), "arms": {a: logit[a] for a, _ in HD_ARMS},
               "p_main": float(logit["S+M+Hd"]["clark_west_p"]), "p_raw": None,
               "p_fake": float(logit["placebo-Hd"]["clark_west_p"]), "p_real_fake": None, "test": "Clark-West"}]

    def scheduled_2010(name: str) -> list[dict]:
        return [r for r in read_csv(RESULTS / "distill" / "networks" / name)
                if r["period"] == "from2010" and r["subset"] == "scheduled"]

    met = {(r["arch"], r["features"]): r for r in scheduled_2010("metrics.csv")}
    comp = {(r["arch"], r["model"], r["against"]): r for r in scheduled_2010("comparison.csv")}
    for arch, label in NETWORK_NAMES.items():
        main = comp[(arch, "S+M+Hd", "S+M")]
        models.append({"name": label, "n": int(met[(arch, "S+M")]["n"]), "arms": {a: met[(arch, a)] for a, _ in HD_ARMS},
                       "p_main": float(main["nw_p_holm"]), "p_raw": float(main["nw_p"]),
                       "p_fake": float(comp[(arch, "placebo-Hd", "S+M")]["nw_p"]),
                       "p_real_fake": float(comp[(arch, "S+M+Hd", "placebo-Hd")]["nw_p"]), "test": "Newey-West"})
    return models


def verdict(p_main: float, p_fake: float, p_real_fake: float | None) -> str:
    """'**passed**' only when the real tone beats no news, beats its placebo, and the placebo does not beat no news."""
    beats_none, fake_quiet = p_main < ALPHA, p_fake >= ALPHA
    beats_fake = p_real_fake is not None and p_real_fake < ALPHA
    if beats_none and beats_fake and fake_quiet:
        return "**passed**"
    if not fake_quiet:
        return "not passed: the fake tone also beats no news"
    if beats_none:
        return "not passed: beats no news, but not shown to beat the fake tone"
    if beats_fake:
        return "not passed: beats the fake tone, but not shown to beat no news"
    if p_real_fake is None:
        return "not passed: not shown to beat no news (check 2a not computed)"
    return "not passed: neither check 1 nor check 2a"


def hd_score_table(column: str, fmt, change, label: str) -> str:
    """One score for the three Hd arms of every model, plus the change from adding the real tone."""
    out = [f"| Model | Meetings tested | {' | '.join(name for _, name in HD_ARMS)} | {label} |",
           "|---|---|---|---|---|---|"]
    for m in hd_models():
        vals = [float(m["arms"][a][column]) for a, _ in HD_ARMS]
        cells = " | ".join(fmt(v, m["n"]) for v in vals)
        out.append(f"| {m['name']} | {m['n']} | {cells} | {change(vals[2] - vals[0])} |")
    return "\n".join(out)


def hd_tests_table() -> str:
    """The two checks for every model, with the verdict."""
    out = ["| Model | Check 1: real tone vs no news | Check 2a: real tone vs fake tone | "
           "Check 2b: fake tone vs no news | Verdict |", "|---|---|---|---|---|"]
    for m in hd_models():
        main = f"p-value {p3(m['p_main'])}" + (f" after Holm adjustment ({p3(m['p_raw'])} before)"
                                               if m["p_raw"] is not None else "")
        main += " → beats" if m["p_main"] < ALPHA else " → not shown"
        rf = ("not computed yet" if m["p_real_fake"] is None else
              f"p-value {p3(m['p_real_fake'])} → " + ("beats" if m["p_real_fake"] < ALPHA else "not shown"))
        fake = f"p-value {p3(m['p_fake'])} → " + ("**fake beats no news**" if m["p_fake"] < ALPHA else
                                                  "does not (good)")
        out.append(f"| {m['name']} ({m['test']}) | {main} | {rf} | {fake} | "
                   f"{verdict(m['p_main'], m['p_fake'], m['p_real_fake'])} |")
    return "\n".join(out)


def headline() -> str:
    """The README's result tables: the single tone Hd from 2010, all four models side by side."""
    return "\n\n".join([
        "**Accuracy** = share of meetings where the outcome the model rated most likely is what the Fed did "
        "(higher is better). In brackets: meetings called right.",
        hd_score_table("accuracy", lambda v, n: f"{v:.1%} ({round(v * n)})",
                       lambda d: f"{d * 100:+.1f} percentage points", "Change from adding real tone"),
        "**Log loss** = the mean of −ln(probability the model gave to what actually happened) (lower is better). "
        "It judges the probabilities, not just the top pick: 0.90 on the right outcome scores 0.105, 0.50 scores "
        "0.693, 0.01 scores 4.605.",
        hd_score_table("log_loss", lambda v, n: f"{v:.3f}", lambda d: f"{d:+.3f}", "Change from adding real tone"),
        "**Rate error** = root mean squared error (RMSE) of the forecast interest rate, in percentage points (lower is "
        "better).",
        hd_score_table("rmse", lambda v, n: f"{v:.4f}", lambda d: f"{d:+.4f}", "Change from adding real tone"),
        "**The two checks.** All p-values are one-sided. Ordered logit: the Clark-West test. Networks: the Newey-West "
        "test with 8 lags on the meeting-by-meeting log-loss difference; for check 1 the p-value is Holm-adjusted "
        "over the 3 networks. A check is passed when the p-value is below 0.05.",
        hd_tests_table(),
    ])


def span_text(days: float) -> str:
    """A number of days in words: weeks below 10 weeks, months above."""
    return f"about {days / 7:.0f} weeks" if days < 70 else f"about {days / 30.44:.1f} months"


def lookback() -> str:
    """The README's look-back tables: meetings read per forecast at every tuning point, and what they mean in time."""
    arms = (("No news", "coral", "S+M"), ("Real tone", "distill", "S+M+Hd"), ("Fake tone", "distill", "placebo-Hd"))
    looks, years = {}, None
    for arch in NETWORK_NAMES:
        for label, study, arm in arms:
            s = json.loads((RESULTS / study / "networks" / f"settings_{arch}_{arm}.json").read_text("utf-8"))
            s = sorted(s.values(), key=lambda v: v["date"])
            looks[(arch, label)] = [v["lookback"] for v in s]
            years = [int(v["date"][:4]) for v in s]
    rows = read_csv(RESULTS / "distill" / "networks" / "preds_tft_S+M+Hd.csv")
    dates = [r["date"] for r in rows]
    spans_cols = [f"{y}-{nxt - 1}" for y, nxt in zip(years, years[1:] + [int(dates[-1][:4]) + 1])]
    out = ["| Model | Version | " + " | ".join(spans_cols) + " |", "|---|---|" + "---|" * len(years),
           "| Ordered logit | every version | " + " | ".join("1" for _ in years) + " |"]
    for arch, name in NETWORK_NAMES.items():
        for label, _, _ in arms:
            out.append(f"| {name} | {label} | " + " | ".join(str(x) for x in looks[(arch, label)]) + " |")

    ds = [date.fromisoformat(d) for d in dates]
    test = [j for j, d in enumerate(ds) if d >= date(2010, 1, 1)]
    used = sorted({x for v in looks.values() for x in v})
    span = ["| Look-back (meetings) | Meetings in the window | Time from the oldest meeting in the window to the "
            "forecast meeting, from 2010 (middle value; shortest to longest) | Chosen in how many of the "
            f"{len(looks) * len(years)} network cells above |", "|---|---|---|---|",
            "| 1 (ordered logit) | the forecast meeting only | 0 days | always, by design |"]
    for L in (2, 4, 8, 12):
        days = sorted((ds[j] - ds[j - L + 1]).days for j in test)
        mid = median(days)
        count = sum(v.count(L) for v in looks.values())
        window = "the forecast meeting and the one before" if L == 2 else f"the forecast meeting and the {L - 1} before"
        span.append(f"| {L} | {window} | {mid:.0f} days, {span_text(mid)} ({days[0]} to {days[-1]} days) | "
                    f"{count} |")
    assert used and set(used) <= {2, 4, 8, 12}
    return "\n\n".join([
        "**How many meetings each model reads for one forecast.** Each cell is the look-back chosen by tuning at the "
        "start of that period and used for every forecast in it. For example, the TFT network with real tone, "
        "forecasting a meeting in 2022, uses the value tuned at the start of 2021.",
        "\n".join(out),
        "**What each look-back means in time.**",
        "\n".join(span),
    ])


def logit_table(period: str) -> str:
    """Ordered logit, one row per arm: scores and the Clark-West p against S+M."""
    rows = {r["model"]: r for r in read_csv(RESULTS / "doctype" / "logit" / f"comparison_{period}.csv")}
    out = ["| Arm | columns | log loss | accuracy | RMSE (pp) | Clark-West p vs S+M | DM-HLN p (log loss) | NW8 p (log loss) |",
           "|---|---|---|---|---|---|---|---|"]
    for arm in ("S+M", "S+M+Hd", "S+M+Hs", "placebo-Hs", "shuffled-Hs"):
        r = rows[arm]
        tests = ("–", "–", "–") if arm == "S+M" else (p3(r["clark_west_p"]), p3(r["dm_logloss_p"]),
                                                      p3(r["nw8_logloss_p"]))
        name = f"**{arm}**" if arm == "S+M+Hs" else arm
        out.append(f"| {name} | {COLUMNS[arm]} | {float(r['log_loss']):.3f} | {pct(r['accuracy'])} | "
                   f"{float(r['rmse']):.3f} | " + " | ".join(tests) + " |")
    return "\n".join(out)


def split_vs_single() -> str:
    """Ordered logit, S+M+Hs against S+M+Hd, both periods (from verdict.json)."""
    v = json.loads((RESULTS / "doctype" / "logit" / "verdict.json").read_text(encoding="utf-8"))
    out = ["| Period | Clark-West p | DM-HLN p (log loss) | NW8 p (log loss) |", "|---|---|---|---|"]
    for period, label in (("from2010", "from 2010 (135 meetings)"), ("full", "full (212 meetings)")):
        s = v[period]["split_vs_single"]
        out.append(f"| {label} | {p3(s['clark_west_p'])} | {p3(s['dm_logloss_p'])} | {p3(s['nw8_logloss_p'])} |")
    return "\n".join(out)


def network_table(period: str) -> str:
    """Networks on scheduled meetings: S+M against each tone arm, its placebo, and the placebo reading."""
    def pick(study: str, name: str) -> list[dict]:
        return [r for r in read_csv(RESULTS / study / "networks" / name)
                if r["period"] == period and r["subset"] == "scheduled"]

    metrics = {(r["arch"], r["features"]): r for r in pick("doctype", "metrics.csv")}
    comp = {(r["arch"], r["model"], r["against"]): r for s in ("doctype", "distill") for r in pick(s, "comparison.csv")}
    n = int(next(iter(metrics.values()))["n"])
    out = [f"Scheduled meetings: {n}.", "",
           "| Network | tone | log loss: S+M → +tone | accuracy: S+M → +tone | NW p vs S+M (Holm over 3) | "
           "placebo vs S+M, p | real vs placebo, p | gain from tone content? |",
           "|---|---|---|---|---|---|---|---|"]
    for arch, label in ARCHS.items():
        base = metrics[(arch, "S+M")]
        for tone in ("Hd", "Hs"):
            arm, plc = f"S+M+{tone}", f"placebo-{tone}"
            main, fake, real = comp[(arch, arm, "S+M")], comp[(arch, plc, "S+M")], comp[(arch, arm, plc)]
            new = metrics[(arch, arm)]
            holm = f" ({p3(main['nw_p_holm'])})" if main["nw_p_holm"] else ""
            gain = float(real["nw_p"]) < 0.05 and float(fake["nw_p"]) >= 0.05
            out.append(f"| {label} | {tone} | {float(base['log_loss']):.3f} → {float(new['log_loss']):.3f} | "
                       f"{pct(base['accuracy'])} → {pct(new['accuracy'])} | {p3(main['nw_p'])}{holm} | {p3(fake['nw_p'])} | "
                       f"{p3(real['nw_p'])} | {'yes' if gain else 'no'} |")
    return "\n".join(out)


def split_vs_single_networks() -> str:
    """Networks from 2010, S+M+Hs against S+M+Hd (Newey-West, scheduled meetings)."""
    rows = [r for r in read_csv(RESULTS / "doctype" / "networks" / "comparison.csv")
            if r["model"] == "S+M+Hs" and r["against"] == "S+M+Hd" and r["subset"] == "scheduled"]
    out = ["| Network | from 2010: NW p | full: NW p |", "|---|---|---|"]
    for arch, label in ARCHS.items():
        p = {r["period"]: p3(r["nw_p"]) for r in rows if r["arch"] == arch}
        out.append(f"| {label} | {p['from2010']} | {p['full']} |")
    return "\n".join(out)


def small_sample() -> str:
    """Small-sample checks of S+M+Hs against S+M on the networks (reported without a rule)."""
    out = ["| Network | period | n | fixed-b p | fixed-m p | RPS: NW p | RPS: fixed-b p |", "|---|---|---|---|---|---|---|"]
    for r in read_csv(RESULTS / "doctype" / "networks" / "small_sample.csv"):
        out.append(f"| {ARCHS[r['arch']]} | {r['period']} | {r['n']} | {p3(r['fixed_b_p'])} | {p3(r['fixed_m_p'])} | "
                   f"{p3(r['rps_nw_p'])} | {p3(r['rps_fixed_b_p'])} |")
    return "\n".join(out)


def tables() -> str:
    """Every generated table, with its heading."""
    return "\n\n".join([
        "### Main result: the single tone Hd from 2010, all four models", headline(),
        "### Ordered logit from 2010 (135 meetings), every arm", logit_table("from2010"),
        "### Ordered logit, full period (212 meetings): reported, no decision rule", logit_table("full"),
        "### Ordered logit, split tone against single tone (S+M+Hs vs S+M+Hd)", split_vs_single(),
        "### Networks from 2010, both tones", network_table("from2010"),
        "### Networks, full period (reported, no decision rule)", network_table("full"),
        "### Networks, split tone against single tone (S+M+Hs vs S+M+Hd)", split_vs_single_networks(),
        "### Networks, small-sample checks of S+M+Hs vs S+M", small_sample(),
    ])


def hyperparameters() -> str:
    """The whole of docs/HYPERPARAMETERS.md: the setting chosen at every tuning point, per network and arm."""
    arms = [("S+M", "coral", "no tone; shared by every study"), ("S+M+Hd", "distill", "single tone, attempt 12b"),
            ("S+M+Hs", "doctype", "split tone, attempt 14b"), ("placebo-Hs", "doctype", "placebo of S+M+Hs")]
    out = ["# Network settings chosen at every tuning point", "",
           "[Back to the README](../README.md) · Explained in [5. The models](5_models.md), section 5.6.", "",
           "Generated by `python scripts/make_results_tables.py` from `results/*/networks/settings_*.json`; do not "
           "edit by hand. One row per tuning point (the first meeting of the year; the settings are used until the "
           "next point). \"layers/heads\" is the LSTM or GRU layer count, or the TFT attention head count. "
           "\"CV log loss\" is the mean validation log loss of the 4 expanding folds for the chosen setting. "
           "\"trials\" counts the 20 Optuna trials that could be scored (a trial whose lookback leaves too few "
           "training sequences is skipped). Settings jump between points (an LSTM's hidden size can go from 64 to "
           "256) because there are so few meetings that tuning is unstable.", ""]
    for arm, study, note in arms:
        out += [f"## {arm} ({note})", "",
                "| Network | tuning point | hidden | layers/heads | dropout | learning rate | weight decay | lookback | "
                "batch | epochs | CV log loss | trials |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for arch, label in ARCHS.items():
            settings = json.loads((RESULTS / study / "networks" / f"settings_{arch}_{arm}.json").read_text("utf-8"))
            for s in sorted(settings.values(), key=lambda s: s["date"]):
                depth = f"heads {s['heads']}" if arch == "tft" else f"layers {s['layers']}"
                out.append(f"| {label} | {s['date']} | {s['hidden']} | {depth} | {s['dropout']:.3f} | {s['lr']:.2e} | "
                           f"{s['weight_decay']:.1e} | {s['lookback']} | {s['batch']} | {s['epochs']} | "
                           f"{s['cv_logloss']:.3f} | {s['n_feasible_trials']} |")
        out.append("")
    return "\n".join(out)


def main(argv: list[str]) -> int:
    """Rewrite the generated tables, or with --check report whether they are current."""
    def fill(path: Path, start: str, end: str, body: str) -> str:
        head, rest = path.read_text(encoding="utf-8").split(start, 1)
        _, tail = rest.split(end, 1)
        return f"{head}{start}\n\n{body}\n\n{end}{tail}"

    readme = fill(README, H_START, H_END, headline())
    head, rest = readme.split(L_START, 1)
    _, tail = rest.split(L_END, 1)
    readme = f"{head}{L_START}\n\n{lookback()}\n\n{L_END}{tail}"
    targets = {README: readme, DOC: fill(DOC, START, END, tables()), HYPER: hyperparameters()}
    if "--check" in argv:
        stale = [p.name for p, new in targets.items() if not p.exists() or p.read_text(encoding="utf-8") != new]
        if stale:
            print(f"out of date: {stale}; run python scripts/make_results_tables.py")
            return 1
        print("README.md, docs/7_results.md and docs/HYPERPARAMETERS.md match results/")
        return 0
    for path, new in targets.items():
        path.write_text(new, encoding="utf-8")
    print("README.md, docs/7_results.md and docs/HYPERPARAMETERS.md rewritten from results/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
